"""AI-15: three modules end to end through integration.Hub — live, no key, timeout, rate limit and replay modes —
with shared versions and one redacted event log. usage: .venv/bin/python evidence/AI-15/integration_eval.py"""
import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'src/retail_bi/ai'))
sys.path.insert(0, str(ROOT / 'src/retail_bi/warehouse'))
import client as C  # noqa: E402
import integration as I  # noqa: E402
from drafts import DraftStore  # noqa: E402
from runtime import open_current  # noqa: E402

tmp = Path(tempfile.mkdtemp())
LOG = tmp / 'events.jsonl'
ok, runs = [], []


def check(name, cond, detail=''):
    ok.append(bool(cond))
    print('PASS' if cond else 'FAIL', name, '' if cond else str(detail)[:300])


con, _ = open_current()
cid = con.execute("SELECT customer_id FROM ads.customer_profile_latest WHERE lifecycle_state = 'dormant' AND orders_all_time >= 2 ORDER BY customer_id LIMIT 1").fetchone()[0]
con.close()
Q, AG = '2026年10月的商品金额是多少？', lambda tag: {'request_id': f'int-{tag}', 'customer_id': cid, 'context': {'consent': True}}


def three(hub, tag, report_mode='live'):
    qa, e1 = hub.run_query(Q)
    rp, e2 = hub.run_report(report_mode)
    ag, e3 = hub.run_agent(AG(tag), store=DraftStore(tmp / f'{tag}.sqlite'))
    runs.extend([{'scenario': tag, **{k: e[k] for k in ('module', 'outcome', 'mode', 'seconds', 'llm')}} for e in (e1, e2, e3)])
    return (qa, e1), (rp, e2), (ag, e3)


def fake(err):
    cfg = C.Config(api_key='sk-test-FAKEKEY0000000', base_url='https://example.invalid/v1', model='fake', allow_paid=True, price_in_per_1k=0.001, price_out_per_1k=0.002, max_retries=1)
    return C.LLMClient(cfg=cfg, transport=C.fixture_transport([err] * 50), log_path=None, sleep=lambda s: None)


# 1. live
live = I.Hub(events=LOG)
(qa, e1), (rp, e2), (ag, e3) = three(live, 'live')
check('live: query answered from the executed query, mode live (LLM note used)', qa['status'] == 'ok' and e1['mode'] == 'live' and e1['llm']['calls'] >= 1, e1)
check('live: weekly report generated by the real LLM and passed the final number check', rp['mode'] == 'live' and not rp['final_check_errors'] and e2['mode'] == 'live' and e2['llm']['calls'] >= 1, e2.get('attempts'))
check('live: agent ran the full workflow with the real LLM and saved a pending draft (not sent)', ag['state'] in ('draft_saved', 'no_action') and e3['mode'] == 'live' and e3['sent'] is False, e3)
check('agent events carry per-step timing, including both LLM steps', all(t['ms'] is not None for t in e3['tools'] if t['tool'] in ('llm_propose', 'llm_copy') or t['ok']), e3['tools'])
check('shared versions: all three results use the same release, and events record dataset/metric/kb/policy versions',
      {e1['result_dataset_version'], e3['result_dataset_version'], e2['result_dataset_version'].split('rel=')[-1] if e2['result_dataset_version'] else None} == {live.v['dataset_version']}
      and all(k in e1['versions'] for k in ('dataset_version', 'metric_version', 'kb_version', 'policy_version')), (e1['result_dataset_version'], e2['result_dataset_version'], e3['result_dataset_version']))
b = live.client.budget()
check('one shared LLM client: calls, tokens and estimated cost add up across modules', b['calls'] == sum(e['llm']['calls'] for e in (e1, e2, e3)) and b['tokens_in'] > 0 and b['cost_usd'] > 0, b)
# 2. no key
nokey = I.Hub(client=C.LLMClient(cfg=C.Config(), log_path=None), events=LOG)
(qa, e1), (rp, e2), (ag, e3) = three(nokey, 'nokey')
check('no key: all three still answer via rules/template and are labelled fallback_no_key, zero model calls',
      qa['status'] == 'ok' and rp['mode'] == 'template' and ag['state'] in ('draft_saved', 'not_eligible') and {e1['mode'], e2['mode'], e3['mode']} == {'fallback_no_key'} and nokey.client.calls == 0,
      [e1['mode'], e2['mode'], e3['mode']])
# 3. timeout and 4. rate limit
for tag, err, want in (('timeout', C.TransportError('network: TimeoutError', True), 'timeout'), ('ratelimit', C.TransportError('HTTP 429', True, 429), 'rate_limited')):
    h = I.Hub(client=fake(err), events=LOG)
    (qa, e1), (rp, e2), (ag, e3) = three(h, tag)
    check(f'{want}: modules fall back (answer/template/rules) and every event is labelled {want}', qa['status'] == 'ok' and rp['mode'] == 'template'
          and {e1['mode'], e2['mode'], e3['mode']} == {want}, [e1['mode'], e2['mode'], e3['mode']])
# 5. replay
rec = json.loads((ROOT / 'reports/ai/weekly_report_replay.json').read_text(encoding='utf-8'))['llm_body']
rp, e2 = I.Hub(client=C.LLMClient(cfg=C.Config(), log_path=None), events=LOG).run_report('replay', replay_text=json.dumps(rec, ensure_ascii=False))
runs.append({'scenario': 'replay', **{k: e2[k] for k in ('module', 'outcome', 'mode', 'seconds', 'llm')}})
check('replay is labelled replay (never live) and makes no model call', e2['mode'] == 'replay' and rp['mode'] == 'replay' and e2['llm']['calls'] == 0, e2['mode'])
# log
lines = LOG.read_text(encoding='utf-8').splitlines()
evs = [json.loads(x) for x in lines]
check('one event per module run (13), each with seconds, llm usage, tools, evidence, errors, versions', len(evs) == 13 and all(all(k in e for k in ('seconds', 'llm', 'tools', 'evidence_ids', 'errors', 'versions', 'mode')) for e in evs), len(evs))
check('event log has no key, no Bearer token and no prompt text', 'sk-test-FAKEKEY' not in LOG.read_text() and 'Bearer' not in LOG.read_text() and '你是' not in LOG.read_text())
check('the five modes are distinguishable in the log', {'live', 'fallback_no_key', 'timeout', 'rate_limited', 'replay'} <= {e['mode'] for e in evs}, {e['mode'] for e in evs})
red = I.redact({'x': 'api_key="sk-abcdefgh12345678"', 'y': ['Bearer abc.def', 3], 'z': None})
check('redact() masks key-like strings inside values and keeps the structure', 'sk-abcdefgh' not in json.dumps(red) and 'abc.def' not in json.dumps(red) and red['y'][1] == 3 and red['z'] is None, red)
out = {'task_id': 'AI-15', 'passed': sum(ok), 'total': len(ok), 'versions': live.v, 'runs': runs, 'live_budget': live.client.budget(),
       'event_example': evs[2], 'scope': '各模式在固定输入上测试；超时与限流用测试替身制造，在线模式为真实 DeepSeek 调用'}
(ROOT / 'reports/ai/integration_evaluation.json').write_text(json.dumps(out, ensure_ascii=False, indent=1, default=str) + '\n', encoding='utf-8')
print(f'{sum(ok)}/{len(ok)} checks passed')
sys.exit(0 if all(ok) else 1)
