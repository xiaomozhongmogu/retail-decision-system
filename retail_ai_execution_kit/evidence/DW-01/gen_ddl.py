"""Generate sql/ddl.sql from the approved data contract plus the hand-written star schema.
ODS columns come straight from the contract (raw names, all VARCHAR); DWD columns use
contract standard names and types. Derived columns are listed explicitly.
usage: .venv/bin/python evidence/DW-01/gen_ddl.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
C = json.loads((ROOT / 'contracts/data_contract.json').read_text(encoding='utf-8'))
SQLT = {'string': 'VARCHAR', 'integer': 'BIGINT', 'decimal(12,2)': 'DECIMAL(12,2)', 'double': 'DOUBLE',
        'boolean': 'BOOLEAN', 'date': 'DATE', 'timestamp': 'TIMESTAMPTZ'}


def col(table, raw):
    c = next(x for x in C['tables'][table]['columns'] if x['raw_name'] == raw)
    return c['standard_name'], SQLT[c['type']]


def cols(table, raws, nn=()):
    out = []
    for r in raws:
        n, t = col(table, r)
        out.append(f'    {n} {t}{" NOT NULL" if n in nn else ""}')
    return out


def J(items):
    """Join column lines with commas placed before any trailing -- comment."""
    out = []
    for i, x in enumerate(items):
        last = i == len(items) - 1
        if '--' in x:
            code, comment = x.split('--', 1)
            out.append(code.rstrip() + ('' if last else ',') + '  --' + comment)
        else:
            out.append(x + ('' if last else ','))
    return '\n'.join(out)


L = ['-- Warehouse DDL (DW-01). Generated by evidence/DW-01/gen_ddl.py from contracts/data_contract.json',
     f'-- contract {C["contract_version"]}; DuckDB dialect. Do not edit by hand; edit the generator.', '',
     'CREATE SCHEMA IF NOT EXISTS ods;', 'CREATE SCHEMA IF NOT EXISTS dwd;', 'CREATE SCHEMA IF NOT EXISTS dws;',
     'CREATE SCHEMA IF NOT EXISTS ads;', 'CREATE SCHEMA IF NOT EXISTS meta;', '']

# ---------------- ODS: raw strings + load metadata
L.append('-- ODS: one table per source file; every source value kept as text; row traceable by (_batch_id, _row_no)')
for t, spec in C['tables'].items():
    body = [f'    "{c["raw_name"]}" VARCHAR' for c in spec['columns']]
    body += ['    _batch_id VARCHAR NOT NULL', '    _source_file VARCHAR NOT NULL', '    _source_sha256 VARCHAR NOT NULL',
             '    _row_no BIGINT NOT NULL', '    _loaded_at TIMESTAMPTZ NOT NULL', '    PRIMARY KEY (_batch_id, _row_no)']
    L += [f'CREATE TABLE IF NOT EXISTS ods.{t} (', J(body), ');']
L += ['CREATE TABLE IF NOT EXISTS meta.load_batch (', J([
    '    batch_id VARCHAR PRIMARY KEY', '    layer_version VARCHAR NOT NULL', '    status VARCHAR NOT NULL CHECK (status IN (\'loading\', \'loaded\'))',
    '    started_at TIMESTAMPTZ NOT NULL', '    finished_at TIMESTAMPTZ']), ');',
    'CREATE TABLE IF NOT EXISTS meta.load_file (', J([
    '    batch_id VARCHAR NOT NULL', '    table_name VARCHAR NOT NULL', '    source_file VARCHAR NOT NULL', '    source_sha256 VARCHAR NOT NULL',
    '    manifest_rows BIGINT NOT NULL', '    loaded_rows BIGINT NOT NULL', '    PRIMARY KEY (batch_id, table_name)']), ');', '']

# ---------------- DWD: star schema
L.append('-- DWD dimensions')
L += ['CREATE TABLE IF NOT EXISTS dwd.dim_date (', J([
    '    date_key INTEGER PRIMARY KEY            -- yyyymmdd', '    calendar_date DATE NOT NULL UNIQUE',
    '    year INTEGER', '    quarter INTEGER', '    month INTEGER', '    month_name VARCHAR', '    week INTEGER', '    day_of_week INTEGER',
    '    day_name VARCHAR', '    is_weekend BOOLEAN', '    is_holiday_period BOOLEAN', '    is_promotion_period BOOLEAN', '    season VARCHAR']), ');']
L += ['CREATE TABLE IF NOT EXISTS dwd.dim_geo (', J([
    '    geo_key VARCHAR PRIMARY KEY             -- region|state|city', '    region VARCHAR NOT NULL', '    state VARCHAR NOT NULL',
    '    city VARCHAR NOT NULL']), ');']
L += ['CREATE TABLE IF NOT EXISTS dwd.dim_customer (', J(
    cols('customers', ['customer_id'], nn={'customer_id'}) +
    ['    geo_key VARCHAR NOT NULL REFERENCES dwd.dim_geo (geo_key)'] +
    cols('customers', ['customer_state', 'customer_region', 'customer_city', 'created_at']) +
    ['    PRIMARY KEY (customer_id)']), ');',
    '-- generator labels (customer_segment, customer_lifecycle_stage) are NOT in dim_customer; lifecycle/segments live in dated snapshot tables']
L += ['CREATE TABLE IF NOT EXISTS dwd.dim_product (', J(
    cols('products', ['product_id', 'product_category', 'product_name', 'product_weight_g', 'product_length_cm', 'product_height_cm',
                      'product_width_cm', 'product_price_base_usd'], nn={'product_id'}) + ['    PRIMARY KEY (product_id)']), ');']
L += ['CREATE TABLE IF NOT EXISTS dwd.dim_seller (', J(
    cols('sellers', ['seller_id'], nn={'seller_id'}) + ['    geo_key VARCHAR NOT NULL REFERENCES dwd.dim_geo (geo_key)'] +
    cols('sellers', ['seller_state', 'seller_region', 'seller_city']) + ['    PRIMARY KEY (seller_id)']), ');', '']

L.append('-- DWD facts')
L += ['CREATE TABLE IF NOT EXISTS dwd.fact_order (', J(
    cols('orders', ['order_id', 'customer_id'], nn={'order_id', 'customer_id'}) +
    ['    purchase_date_key INTEGER NOT NULL REFERENCES dwd.dim_date (date_key)'] +
    cols('orders', ['order_purchase_timestamp', 'order_approved_at', 'order_delivered_carrier_date', 'order_delivered_customer_date',
                    'order_estimated_delivery_date', 'order_status']) +
    ['    merch_usd DECIMAL(18,2) NOT NULL          -- sum of line item_price_usd',
     '    shipping_usd DECIMAL(18,2) NOT NULL       -- sum of line item_shipping_usd',
     '    order_value_usd DECIMAL(18,2) NOT NULL    -- merch + shipping',
     '    item_lines INTEGER NOT NULL',
     '    payment_value_usd DECIMAL(18,2) NOT NULL  -- sum of payments, reconciliation only',
     '    payment_rows INTEGER NOT NULL',
     '    review_score INTEGER                      -- at most one review per order',
     '    review_created_date DATE',
     '    late_by_date BOOLEAN                      -- delivered date > estimated date; NULL if not delivered',
     '    late_by_days BOOLEAN                      -- generator definition; NULL if not delivered',
     '    PRIMARY KEY (order_id)',
     '    FOREIGN KEY (customer_id) REFERENCES dwd.dim_customer (customer_id)']), ');',
    '-- validity is time dependent: an order is a valid purchase at as_of iff approved_ts < as_of (transaction-rules-v1)']
L += ['CREATE TABLE IF NOT EXISTS dwd.fact_order_line (', J(
    cols('order_items', ['order_id', 'order_item_id'], nn={'order_id', 'order_item_seq'}) +
    ['    customer_id VARCHAR NOT NULL', '    purchase_date_key INTEGER NOT NULL REFERENCES dwd.dim_date (date_key)'] +
    cols('order_items', ['product_id', 'seller_id', 'seller_product_id', 'item_price_usd', 'shipping_cost_usd', 'item_total_usd']) +
    ['    PRIMARY KEY (order_id, order_item_seq)',
     '    FOREIGN KEY (order_id) REFERENCES dwd.fact_order (order_id)',
     '    FOREIGN KEY (product_id) REFERENCES dwd.dim_product (product_id)',
     '    FOREIGN KEY (seller_id) REFERENCES dwd.dim_seller (seller_id)']), ');']
L += ['CREATE TABLE IF NOT EXISTS dwd.fact_payment (', J(
    cols('payments', ['order_id', 'payment_sequential', 'payment_type', 'payment_installments', 'payment_value_usd'], nn={'order_id', 'payment_seq'}) +
    ['    PRIMARY KEY (order_id, payment_seq)', '    FOREIGN KEY (order_id) REFERENCES dwd.fact_order (order_id)']), ');']
L += ['CREATE TABLE IF NOT EXISTS dwd.fact_fulfillment (', J(
    cols('shipping', ['order_id', 'shipping_distance_band', 'shipping_zone', 'estimated_delivery_days', 'shipping_cost_usd'], nn={'order_id'}) +
    ['    delivery_days_floor INTEGER               -- recomputed from timestamps', '    PRIMARY KEY (order_id)',
     '    FOREIGN KEY (order_id) REFERENCES dwd.fact_order (order_id)']), ');', '']

L.append('-- DWS (built by DW-04/DW-05; additive measures and distinct counts are kept apart)')
L += ['CREATE TABLE IF NOT EXISTS dws.sales_daily_category_region (', J([
    '    date_key INTEGER NOT NULL', '    product_category VARCHAR NOT NULL', '    customer_region VARCHAR NOT NULL',
    '    valid_lines BIGINT NOT NULL               -- additive', '    merch_usd DECIMAL(18,2) NOT NULL           -- additive',
    '    shipping_usd DECIMAL(18,2) NOT NULL        -- additive',
    '    orders_containing BIGINT NOT NULL          -- distinct orders at this grain; NOT additive across categories',
    '    PRIMARY KEY (date_key, product_category, customer_region)']), ');']
L += ['CREATE TABLE IF NOT EXISTS dws.customer_daily (', J([
    '    customer_id VARCHAR NOT NULL', '    date_key INTEGER NOT NULL', '    valid_orders BIGINT NOT NULL', '    merch_usd DECIMAL(18,2) NOT NULL',
    '    PRIMARY KEY (customer_id, date_key)']), ');']
L += ['CREATE TABLE IF NOT EXISTS dws.product_daily (', J([
    '    product_id VARCHAR NOT NULL', '    date_key INTEGER NOT NULL', '    valid_lines BIGINT NOT NULL', '    merch_usd DECIMAL(18,2) NOT NULL',
    '    orders_containing BIGINT NOT NULL', '    PRIMARY KEY (product_id, date_key)']), ');']
L += ['CREATE TABLE IF NOT EXISTS dws.customer_snapshot (', J([
    '    customer_id VARCHAR NOT NULL', '    as_of TIMESTAMPTZ NOT NULL', '    feature_window_start TIMESTAMPTZ NOT NULL',
    '    recency_days DOUBLE', '    frequency_90d BIGINT NOT NULL', '    monetary_90d_usd DECIMAL(18,2) NOT NULL',
    '    orders_all_time BIGINT NOT NULL', '    merch_all_time_usd DECIMAL(18,2) NOT NULL', '    first_purchase_ts TIMESTAMPTZ',
    '    tenure_days DOUBLE', '    lifecycle_state VARCHAR                    -- rule-based (EDA-05), never the generator label',
    '    snapshot_version VARCHAR NOT NULL', '    PRIMARY KEY (customer_id, as_of)']), ');']
L += ['CREATE TABLE IF NOT EXISTS dws.label_repurchase (', J([
    '    customer_id VARCHAR NOT NULL', '    as_of TIMESTAMPTZ NOT NULL', '    horizon_days INTEGER NOT NULL', '    y BOOLEAN NOT NULL',
    '    label_matured_at TIMESTAMPTZ NOT NULL', '    label_version VARCHAR NOT NULL',
    '    PRIMARY KEY (customer_id, as_of, horizon_days, label_version)']), ');', '',
    '-- ADS: views over DWD/DWS defined in sql/ads.sql (DW-06); the AI query layer may read only views listed in meta.allowed_view',
    'CREATE TABLE IF NOT EXISTS meta.allowed_view (view_name VARCHAR PRIMARY KEY, purpose VARCHAR NOT NULL);', '']
(ROOT / 'sql').mkdir(exist_ok=True)
(ROOT / 'sql/ddl.sql').write_text('\n'.join(L), encoding='utf-8')
print('written', len(L), 'lines')
